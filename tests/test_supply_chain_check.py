# ---------------- 对账 ----------------

def test_a_package_absent_from_the_lock_is_a_hard_failure():
    entries, floor = sc.parse_lock(_lock("alembic==1.18.5 \\", "    --hash=sha256:a"))
    failures, notes, _ = sc.compare(
        entries, floor, _snapshot({"alembic": "1.18.5", "pytest": "9.1.1"}))
    assert _kinds(failures) == [("unlocked", "pytest")]
    assert notes == []


def test_a_version_the_lock_does_not_allow_is_a_hard_failure():
    entries, floor = sc.parse_lock(_lock("alembic==1.18.5 \\", "    --hash=sha256:a"))
    failures, _, _ = sc.compare(entries, floor, _snapshot({"alembic": "1.18.4"}))
    assert _kinds(failures) == [("drift", "alembic")]
    assert "1.18.4" in failures[0].detail and "1.18.5" in failures[0].detail


def test_same_name_two_versions_is_matched_by_set_membership():
    """universal 锁按 marker 分叉出两条 websockets;两边都得算对上。

    单值等号比会让 3.10 的机器看到 17.0.1、3.12 的机器看到 16.1.1，各误报一次。
    """
    entries, floor = sc.parse_lock(_lock(
        "websockets==16.1.1 ; python_full_version < '3.11' \\", "    --hash=sha256:a",
        "websockets==17.0.1 ; python_full_version >= '3.11' \\", "    --hash=sha256:b"))
    for env, installed in ((LINUX_310, "16.1.1"), (MACOS_314, "17.0.1")):
        failures, notes, _ = sc.compare(
            entries, floor, _snapshot({"websockets": installed}, env))
        assert failures == [] and notes == []
    failures, _, _ = sc.compare(
        entries, floor, _snapshot({"websockets": "16.1"}, LINUX_310))
    assert _kinds(failures) == [("drift", "websockets")]


def test_absent_is_a_note_when_the_marker_is_false_and_a_failure_when_true():
    entries, floor = sc.parse_lock(_lock(
        "colorama==0.4.6 ; sys_platform == 'win32' \\", "    --hash=sha256:a",
        "alembic==1.18.5 \\", "    --hash=sha256:b"))
    failures, notes, _ = sc.compare(entries, floor, _snapshot({"alembic": "1.18.5"}))
    assert _kinds(notes) == [("absent", "colorama")]
    assert failures == []

    failures, notes, _ = sc.compare(entries, floor, _snapshot({"colorama": "0.4.6"},
                                                              WINDOWS_312))
    assert _kinds(failures) == [("absent", "alembic")]
    assert notes == []


def test_an_unparseable_marker_fails_the_check_rather_than_being_skipped():
    entries, floor = sc.parse_lock(_lock(
        "anyio==4.14.2 ; extra == 'standard' \\", "    --hash=sha256:a"))
    failures, _, _ = sc.compare(entries, floor, _snapshot({"anyio": "4.14.2"}))
    assert _kinds(failures) == [("marker", "anyio")]


def test_python_below_the_locks_floor_is_a_hard_failure():
    text = _lock("#    uv pip compile --python-version 3.10 --generate-hashes",
                 "alembic==1.18.5 \\", "    --hash=sha256:a")
    entries, floor = sc.parse_lock(text)
    old = {**LINUX_310, "python_version": "3.9", "python_full_version": "3.9.18"}
    failures, _, _ = sc.compare(entries, floor,
                                _snapshot({"alembic": "1.18.5"}, old))
    assert ("floor", "python") in _kinds(failures)
    failures, _, _ = sc.compare(entries, floor, _snapshot({"alembic": "1.18.5"}))
    assert ("floor", "python") not in _kinds(failures)


def test_a_lock_without_hashes_fails_before_anything_else_matters():
    entries, floor = sc.parse_lock(_lock("alembic==1.18.5"))
    failures, _, _ = sc.compare(entries, floor, _snapshot({"alembic": "1.18.5"}))
    assert _kinds(failures) == [("hashed", "锁本身")]


# ---------------- 真锁 + 真解释器 ----------------

def test_the_shipped_lock_is_fully_hashed_and_every_marker_evaluates():
    """挡两种回归：有人不带 --generate-hashes 重出锁；uv 换出求值器不认识的 marker。"""
    entries, floor = sc.parse_lock(REAL_LOCK.read_text(encoding="utf-8"))
    assert floor is not None, "锁头部必须留下 --python-version，下限是判据不是装饰"
    assert entries, "锁不该是空的"
    for entry in entries:
        assert entry.hashes, f"{entry.raw_name} 没有 --hash"
        if entry.marker:
            for env in (LINUX_310, MACOS_314, WINDOWS_312):
                sc.evaluate_marker(entry.marker, env)       # 不抛即通过


def test_probe_reports_the_interpreter_that_actually_ran_it():
    snapshot = sc.probe(sys.executable)
    assert snapshot["environment"]["python_full_version"] == (
        ".".join(str(n) for n in sys.version_info[:3]))
    assert "pytest" in {sc.canonical(name) for name in snapshot["distributions"]}


def test_cli_exits_nonzero_and_prints_json_when_the_environment_drifts(tmp_path):
    lock = tmp_path / "lock.txt"
    lock.write_text(_lock("alembic==1.18.5 \\", "    --hash=sha256:a"), encoding="utf-8")
    probe = tmp_path / "probe.json"
    probe.write_text(__import__("json").dumps(
        _snapshot({"alembic": "1.18.5", "pytest": "9.1.1"})), encoding="utf-8")

    script = Path(sc.__file__)
    done = subprocess.run(
        [sys.executable, str(script), "--lock", str(lock),
         "--probe-json", str(probe), "--json"],
        capture_output=True, text=True, timeout=120)
    assert done.returncode == 1
    report = __import__("json").loads(done.stdout)
    assert report["ok"] is False
    assert [f["name"] for f in report["failures"]] == ["pytest"]


def test_cli_requires_exactly_one_source():
    script = Path(sc.__file__)
    done = subprocess.run([sys.executable, str(script)],
                          capture_output=True, text=True, timeout=120)
    assert done.returncode == 2 and "二选一" in done.stderr
