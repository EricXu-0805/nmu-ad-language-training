"""运行环境 ↔ 哈希锁对账。

这套用例守的是三件事：锁本身必须带哈希、marker 必须真求值（不是当真或当假
糊过去）、同名多版本必须按集合判。第三条尤其容易写错——universal 锁里
websockets 有两条（<3.11 一条、>=3.11 一条），拿单值等号比会在半数机器上误报。
"""
from __future__ import annotations

from pathlib import Path
import subprocess
import sys

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))

import supply_chain_check as sc                             # noqa: E402

REAL_LOCK = Path(__file__).resolve().parents[1] / "requirements-deploy.lock.txt"

LINUX_310 = {
    "implementation_name": "cpython",
    "os_name": "posix",
    "platform_machine": "x86_64",
    "platform_python_implementation": "CPython",
    "platform_system": "Linux",
    "python_full_version": "3.10.12",
    "python_version": "3.10",
    "sys_platform": "linux",
}
MACOS_314 = {**LINUX_310, "platform_machine": "arm64", "platform_system": "Darwin",
             "python_full_version": "3.14.5", "python_version": "3.14",
             "sys_platform": "darwin"}
WINDOWS_312 = {**LINUX_310, "platform_machine": "AMD64", "os_name": "nt",
               "platform_system": "Windows", "python_full_version": "3.12.8",
               "python_version": "3.12", "sys_platform": "win32"}


def _lock(*lines: str) -> str:
    return "\n".join(lines) + "\n"


def _snapshot(distributions: dict[str, str], environment=None) -> dict:
    return {"environment": dict(environment or LINUX_310),
            "distributions": dict(distributions)}


def _kinds(findings) -> list[tuple[str, str]]:
    return sorted((f.kind, f.name) for f in findings)


# ---------------- 解析 ----------------

def test_parse_lock_reads_version_marker_hashes_and_floor():
    entries, floor = sc.parse_lock(_lock(
        "# This file was autogenerated by uv via the following command:",
        "#    uv pip compile requirements-deploy.txt --universal "
        "--python-version 3.10 --generate-hashes -o requirements-deploy.lock.txt",
        "alembic==1.18.5 \\",
        "    --hash=sha256:aaa \\",
        "    --hash=sha256:bbb",
        "    # via -r requirements-deploy.txt",
        "colorama==0.4.6 ; sys_platform == 'win32' \\",
        "    --hash=sha256:ccc",
    ))
    assert floor == (3, 10)
    assert [(e.name, e.version, e.marker, len(e.hashes)) for e in entries] == [
        ("alembic", "1.18.5", None, 2),
        ("colorama", "0.4.6", "sys_platform == 'win32'", 1),
    ]


def test_parse_lock_refuses_a_line_it_does_not_understand():
    with pytest.raises(ValueError, match="看不懂的锁行"):
        sc.parse_lock(_lock("alembic>=1.18.5"))          # 锁必须是精确钉版


def test_canonical_name_folds_the_three_separators():
    assert sc.canonical("Piper_TTS") == sc.canonical("piper-tts") == "piper-tts"
    assert sc.canonical("zope.interface") == "zope-interface"


# ---------------- marker 求值 ----------------

@pytest.mark.parametrize("marker, env, expected", [
    ("sys_platform == 'win32'", LINUX_310, False),
    ("sys_platform == 'win32'", WINDOWS_312, True),
    ("python_full_version < '3.11'", LINUX_310, True),
    ("python_full_version < '3.11'", MACOS_314, False),
    ("python_full_version >= '3.11'", LINUX_310, False),
    ("implementation_name != 'pypy'", LINUX_310, True),
    ("platform_python_implementation != 'PyPy' and implementation_name != 'PyPy'",
     LINUX_310, True),
    ("platform_python_implementation != 'PyPy' and sys_platform != 'cygwin' "
     "and sys_platform != 'win32'", WINDOWS_312, False),
    ("platform_machine == 'AMD64' or platform_machine == 'aarch64' "
     "or platform_machine == 'x86_64'", LINUX_310, True),
    ("platform_machine == 'AMD64' or platform_machine == 'aarch64' "
     "or platform_machine == 'x86_64'", MACOS_314, False),
])
def test_evaluate_marker_on_the_forms_the_real_lock_uses(marker, env, expected):
    assert sc.evaluate_marker(marker, env) is expected


@pytest.mark.parametrize("marker", [
    "extra == 'standard'",                                  # 未知变量
    "python_version in '3.10 3.11'",                        # 未支持的运算符
    "(sys_platform == 'win32')",                            # 括号
    "sys_platform",                                         # 不成子句
])
def test_evaluate_marker_raises_instead_of_guessing(marker):
    with pytest.raises(sc.MarkerError):
        sc.evaluate_marker(marker, LINUX_310)


def test_version_key_puts_a_prerelease_before_its_release():
    assert sc._version_key("3.15.0b1") < sc._version_key("3.15.0")
    assert sc._version_key("3.9") < sc._version_key("3.10")   # 不是字符串比较
